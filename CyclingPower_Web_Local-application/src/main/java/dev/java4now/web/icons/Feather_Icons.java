    public static String getChar(String iconName) {
        String escapeCode = ICON_TO_CHAR.getOrDefault(iconName, "\\e11d");
        return convertEscapeCodeToChar(escapeCode);
    }

    private static String convertEscapeCodeToChar(String escapeCode) {
        // Remove the "\\u" prefix and parse the hex code
        String hexCode = escapeCode.replace("\\", "");
        try {
            int codePoint = Integer.parseInt(hexCode, 16);
            return new String(Character.toChars(codePoint));
        } catch (NumberFormatException e) {
            Console.log("Invalid Unicode escape code: " + escapeCode);
            return "Invalid";
        }
    }
